/**
 * Compiles the shared security headers into `app/out/_headers` for Cloudflare Pages.
 *
 *   node scripts/write-cloudflare-headers.mjs
 *
 * Run after `next build` and before `scripts/check-export.mjs`, which fails if the file is missing
 * or has lost a header that markup cannot express.
 *
 * ## Why this is generated rather than committed
 *
 * A committed `_headers` is a second copy of a security policy, and the two copies drift in the
 * direction that is hard to notice: the local server keeps demonstrating a correct CSP while the
 * public site quietly serves something weaker. Generating it from `security-headers.mjs` makes
 * drift impossible rather than unlikely, and it means a reviewer reads the policy in one place.
 *
 * It also lands inside `app/out`, which is gitignored build output. Nothing to review in a diff,
 * nothing to forget to regenerate.
 *
 * ## What Cloudflare does and does not do with this
 *
 * Pages applies `_headers` to matched paths and strips the file from the served output. The `/*`
 * rule covers every route including the HTML that Next emits as `pins.html` and Pages serves at
 * `/pins`.
 *
 * One thing it will not do: `_headers` cannot set a header on a response Pages generates itself for
 * a path that does not exist. That is fine here — a 404 carrying no CSP is not a risk surface,
 * because there is no attacker-controlled content in it.
 *
 * ## The cache rule is deliberate and is not a performance tweak
 *
 * Next fingerprints everything under `/_next/static/`, so those files are immutable by
 * construction and get a year. Everything else gets `no-store`.
 *
 * That looks aggressive for a static site until you consider what this site is. The HTML inlines
 * `NEXT_PUBLIC_*` configuration at build time — the registry address, the guard address, the pin
 * ids. A cached page therefore encodes *which contracts the dashboard reads*, and after the
 * pending redeploy those values change. A reader holding a stale page would be shown a registry
 * that no longer matches the code, with no indication anything was wrong, on a site whose entire
 * argument is that you should verify rather than trust what you are shown. Correctness of the
 * displayed configuration beats a warm cache.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { SECURITY_HEADERS } from "./security-headers.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "app", "out");
const TARGET = join(OUT, "_headers");

/** Cloudflare's format: a path pattern, then indented `Name: value` lines. */
function rule(pattern, headers) {
  const lines = Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`);
  return [pattern, ...lines].join("\n");
}

const body = [
  "# Generated by scripts/write-cloudflare-headers.mjs. Do not edit.",
  "# The policy lives in scripts/security-headers.mjs, which the local reference server",
  "# (scripts/serve-export.mjs) reads from too, so the two cannot disagree.",
  "",
  rule("/*", {
    ...SECURITY_HEADERS,
    // See the note above: the HTML carries build-time contract addresses, so a stale copy
    // misrepresents which chain state is being read.
    "cache-control": "no-store",
  }),
  "",
  rule("/_next/static/*", {
    // Fingerprinted filenames, so the content cannot change under a given URL.
    "cache-control": "public, max-age=31536000, immutable",
  }),
  "",
].join("\n");

mkdirSync(OUT, { recursive: true });
writeFileSync(TARGET, body, "utf8");

process.stdout.write(`wrote ${TARGET}\n`);
for (const name of Object.keys(SECURITY_HEADERS)) process.stdout.write(`  ${name}\n`);
